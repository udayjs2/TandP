// Pick the letter from the designation text typed on the form (Telugu or English keywords).
export function guessLetterType(designation = "") {
  const d = String(designation).toLowerCase();
  if (/general\s*manager|\bgm\b|జనరల్/.test(d)) return "gm";
  if (/production\s*manager|\bpm\b|ప్రొడక్షన్\s*మేనేజర్/.test(d)) return "pm";
  if (/sales/.test(d) && /manager|head|lead/.test(d)) return "sales";
  if (/\bhr\b|human\s*resource|హెచ్‌?ఆర్/.test(d)) return "hr";
  if (/team\s*lead|\btl\b|supervisor|టీమ్\s*లీడ్|సూపర్‌?వైజర్/.test(d)) return "tl";
  if (/finance|account|ఫైనాన్స్|అకౌంట్/.test(d)) return "finance";
  return "staff";
}

